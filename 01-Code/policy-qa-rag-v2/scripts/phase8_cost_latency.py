"""Phase 8 - cost and latency analysis from RECORDED measurements only (no retrieval run, no LLM call).

Sources (all already saved and hash-protected):
  activities/b-hybrid-search-rrf/results/hybrid-retrieval.json   component benchmark (100 timed searches per cell)
  activities/c-cross-encoder-reranking/results/reranking.json     rerank benchmark (100 timed searches per cell)
  results/phase7/retrieval.json                                   18 configs x 30 queries (single pass)
  results/phase7/answers.jsonl                                    real-LLM answers (v1 complete, v2 partial)
  results/dev-answer-eval/real-smoke-1/records.jsonl              real-LLM dev smoke test (both configs complete)
  results/cross-encoder-model-info.json                           one-time download
Every number is labelled MEASURED, ESTIMATE (derived from measurements x published price) or UNAVAILABLE.

    .venv/bin/python scripts/phase8_cost_latency.py
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from rag_v2.pricing import PRICING_USD_PER_MILLION, estimate_cost_usd  # noqa: E402

OUT = PROJECT_ROOT / "results" / "phase8"
MODEL = "openai/gpt-oss-120b"
V1, V2 = "v1_paragraph_800_150+dense", "v1_paragraph_800_150+hybrid+rerank"
V3 = "recursive_800_100+hybrid+rerank"
ANSWER_CONFIGS = (V1, V2, V3)
TPD_LIMIT = 200_000  # from the provider's own rate-limit message recorded in 03-Evidence/30-... (free tier)


def load_jsonl(path):
    latest = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        latest[(r["config"], r.get("id") or r.get("query_id"))] = r
    return [r for r in latest.values() if "error" not in r]


def pct(v, q):
    s = sorted(v)
    return s[min(len(s) - 1, round(q * (len(s) - 1)))]


def stats(v):
    return (
        {"n": len(v), "median": statistics.median(v), "p95": pct(v, 0.95), "mean": statistics.mean(v)}
        if v
        else None
    )


def fmt(x, nd=1):
    return "—" if x is None else f"{x:.{nd}f}"


def main() -> int:
    p3 = json.loads(
        (PROJECT_ROOT / "activities/b-hybrid-search-rrf/results/hybrid-retrieval.json").read_text()
    )
    p4 = json.loads(
        (PROJECT_ROOT / "activities/c-cross-encoder-reranking/results/reranking.json").read_text()
    )
    p7r = json.loads((PROJECT_ROOT / "results/phase7/retrieval.json").read_text())
    model_info = json.loads((PROJECT_ROOT / "results/cross-encoder-model-info.json").read_text())
    p7a = load_jsonl(PROJECT_ROOT / "results/phase7/answers.jsonl")
    smoke = load_jsonl(PROJECT_ROOT / "results/dev-answer-eval/real-smoke-1/records.jsonl")
    price = PRICING_USD_PER_MILLION[MODEL]
    L = [
        "# Phase 8 – Cost and Latency Analysis (generated from recorded measurements)",
        "",
        "> Generated by `scripts/phase8_cost_latency.py`. No retrieval or LLM call was made to produce it.",
        "> **MEASURED** = recorded timings/tokens; **ESTIMATE** = measured tokens × published list price; "
        "**UNAVAILABLE** = not measured (stated, never filled in).",
        "",
        "Hardware: Apple M3, 4 CPU threads, CPU-only inference; single process; Python 3.12.16.",
        "",
    ]

    # ---- 1. retrieval stages (benchmarks: 100 timed searches per cell)
    L += [
        "## 1. Retrieval latency per stage — MEASURED (benchmarks, 100 timed searches per cell after warm-up)",
        "",
        "| Chunking | Query embedding | Chroma search | BM25 | RRF | Cross-encoder (10 pairs) | Hybrid total | Hybrid + rerank total |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    bench = {}
    for n in p3["latency_not_hashed"]["per_component"]:
        c3, c4 = p3["latency_not_hashed"]["per_component"][n], p4["latency_not_hashed"]["per_stage"][n]
        bench[n] = {
            "embed": c3["query_embedding"]["median_ms"],
            "search": c3["vector_search"]["median_ms"],
            "bm25": c3["bm25"]["median_ms"],
            "rrf": c3["fusion"]["median_ms"],
            "rerank": c4["rerank"]["median_ms"],
            "hybrid": c4["hybrid_total"]["median_ms"],
            "total": c4["total"]["median_ms"],
            "rerank_p95": c4["rerank"]["p95_ms"],
            "total_p95": c4["total"]["p95_ms"],
        }
        b = bench[n]
        L.append(
            f"| `{n}` | {b['embed']:.2f} | {b['search']:.2f} | {b['bm25']:.3f} | {b['rrf']:.3f} | {b['rerank']:.1f} "
            f"(p95 {b['rerank_p95']:.1f}) | {b['hybrid']:.1f} | {b['total']:.1f} (p95 {b['total_p95']:.1f}) |"
        )
    rr = [b["rerank"] for b in bench.values()]
    ratio = [b["rerank"] / b["hybrid"] for b in bench.values()]
    L += [
        "",
        f"Median ms. Hybrid adds BM25 + RRF ≈ 0.1 ms to dense retrieval; the cross-encoder adds {min(rr):.0f}–{max(rr):.0f} ms "
        f"({min(ratio):.1f}–{max(ratio):.1f}× the hybrid retrieval time) — the only material retrieval-side latency cost of v2.",
        "",
    ]

    # ---- 2. Phase 7 single-pass retrieval timings, all 18 configs
    L += [
        "## 2. Retrieval latency on the 30 evaluation queries — MEASURED (single pass, median ms)",
        "",
        "| Config | Median retrieval ms | vs v1 |",
        "|---|---:|---:|",
    ]
    v1r = p7r["configs"][V1]["median_ms"]["retrieval_total"]
    for n, c in p7r["configs"].items():
        m = c["median_ms"]["retrieval_total"]
        L.append(f"| `{n}` | {m:.1f} | {m / v1r:.2f}× |")

    # ---- 3. LLM tokens and latency
    def usage(rs):
        real = [r for r in rs if r["llm_usage"].get("llm_called") and not r["llm_usage"].get("cached")]
        called = [r for r in rs if r["llm_usage"].get("llm_called")]
        return real, called

    L += ["", "## 3. LLM generation — MEASURED", ""]
    L += [
        "| Run | Config | Completeness | LLM calls (real / cached / not called) | Mean prompt tokens | Mean completion tokens | "
        "Median generation ms | p95 generation ms | Median end-to-end ms |",
        "|---|---|---|---|---:|---:|---:|---:|---:|",
    ]
    rows_out = {}
    for run, recs, n_total in (
        ("Phase 7 (30 eval queries)", p7a, 30),
        ("Phase 6 smoke (8 dev queries)", smoke, 8),
    ):
        for cfg in ANSWER_CONFIGS:
            rs = [r for r in recs if r["config"] == cfg]
            if not rs:
                continue
            real, called = usage(rs)
            g = stats([r["timings_ms"]["generation"] for r in real])
            tot = stats([r["timings_ms"]["total"] for r in real])
            pt = statistics.mean(r["llm_usage"]["prompt_tokens"] for r in called) if called else None
            ct = statistics.mean(r["llm_usage"]["completion_tokens"] for r in called) if called else None
            done = "complete" if len(rs) == n_total else f"PARTIAL ({len(rs)}/{n_total})"
            rows_out[(run, cfg)] = {"pt": pt, "ct": ct, "gen": g, "tot": tot, "real": len(real), "n": len(rs)}
            L.append(
                f"| {run} | `{cfg}` | {done} | {len(real)} / {sum(r['llm_usage'].get('cached', False) for r in rs)} / "
                f"{len(rs) - len(called)} | {fmt(pt, 0)} | {fmt(ct, 0)} | {fmt(g and g['median'], 0)} | "
                f"{fmt(g and g['p95'], 0)} | {fmt(tot and tot['median'], 0)} |"
            )
    L.append("")
    for cfg in ANSWER_CONFIGS:
        real, _ = usage([r for r in p7a if r["config"] == cfg])
        g = [r["timings_ms"]["generation"] for r in real]
        times = sorted(r["recorded_utc"] for r in p7a if r["config"] == cfg)
        clean = [x for x in g if x < 2000]
        L.append(
            f"- `{cfg}` (recorded {times[0][:16]}–{times[-1][:16]} UTC): {sum(x > 4000 for x in g)} of {len(g)} real "
            f"calls took > 4 s (max {max(g) / 1000:.1f} s), consistent with free-tier rate-limit waits; uncontended "
            f"calls (< 2 s): median {statistics.median(clean):.0f} ms (n = {len(clean)})."
            if clean
            else ""
        )
    L += [
        "- The three answer runs were made at different times under different quota pressure, and cached answers are "
        "excluded from latency, so **Phase 7 LLM and end-to-end latencies are not comparable between configurations**. "
        "The clean like-for-like LLM comparison is the Phase 6 smoke test (same 8 queries, no quota pressure); clean "
        "retrieval latency comes from the Phase 3/4 benchmarks (section 1).",
        "- Generation dominates end-to-end time (≈ 1 s uncontended vs ≈ 20–90 ms retrieval).",
        "",
    ]

    # ---- 4. paired token comparison on identical queries
    by = {(r["config"], r["id"]): r for r in p7a}
    L += [
        "## 4. Prompt size vs v1 on identical queries — MEASURED",
        "",
        "| Config | Queries (both called the LLM) | Mean prompt tokens v1 | Mean prompt tokens config | Identical context |",
        "|---|---:|---:|---:|---:|",
    ]
    for cfg in (V2, V3):
        ids = sorted({i for c, i in by if c == cfg} & {i for c, i in by if c == V1})
        pairs = [
            (by[(V1, i)], by[(cfg, i)])
            for i in ids
            if by[(V1, i)]["llm_usage"].get("llm_called") and by[(cfg, i)]["llm_usage"].get("llm_called")
        ]
        L.append(
            f"| `{cfg}` | {len(pairs)} | {statistics.mean(a['llm_usage']['prompt_tokens'] for a, _ in pairs):.0f} | "
            f"{statistics.mean(b['llm_usage']['prompt_tokens'] for _, b in pairs):.0f} | "
            f"{sum(a['context'] == b['context'] for a, b in pairs)}/{len(pairs)} |"
        )
    L += [
        "",
        "Context size is fixed at 4 chunks, so hybrid retrieval, reranking and chunking change *which* chunks are "
        "sent, not how many; prompt size changes only with chunk length.",
        "",
    ]

    # ---- 5. cost
    v1rows = [r for r in p7a if r["config"] == V1]
    _, called = usage(v1rows)
    pt, ct = (
        sum(r["llm_usage"]["prompt_tokens"] for r in called),
        sum(r["llm_usage"]["completion_tokens"] for r in called),
    )
    per_q = estimate_cost_usd(MODEL, pt, ct) / len(v1rows)
    spent = [r for r in p7a + smoke if r["llm_usage"].get("llm_called") and not r["llm_usage"].get("cached")]
    sp = sum(r["llm_usage"]["prompt_tokens"] for r in spent)
    sc = sum(r["llm_usage"]["completion_tokens"] for r in spent)
    tok_per_q = (pt + ct) / len(called)
    L += [
        "## 5. Cost",
        "",
        f"Price used for estimates: {MODEL} ${price['input']}/1M input, ${price['output']}/1M output tokens "
        f"({price['source']}, retrieved {price['retrieved']}; verify against the live page).",
        "",
        "| Item | Value | Type |",
        "|---|---|---|",
        f"| Tokens per answered query (v1, 30 eval queries) | {pt / len(called):.0f} prompt + {ct / len(called):.0f} completion | MEASURED |",
        f"| LLM calls avoided by the dense gate (v1, 30 queries) | {len(v1rows) - len(called)} | MEASURED |",
        f"| Cost per query (v1) | ${per_q:.6f} | ESTIMATE |",
        f"| Cost per 1,000 queries (v1) | ${per_q * 1000:.2f} | ESTIMATE (linear extrapolation) |",
        *[
            f"| Cost per query `{c}` (30 queries, incl. cached-equivalent) | "
            f"${sum(r['estimated_cost_usd'] or 0 for r in p7a if r['config'] == c) / 30:.6f} | ESTIMATE |"
            for c in ANSWER_CONFIGS
        ],
        *[
            f"| LLM calls skipped by the dense gate `{c}` (30 queries) | "
            f"{sum(1 for r in p7a if r['config'] == c and not r['llm_usage'].get('llm_called'))} | MEASURED |"
            for c in ANSWER_CONFIGS
        ],
        f"| Tokens actually spent on Day 13 real calls (smoke + Phase 7) | {sp:,} prompt + {sc:,} completion | MEASURED |",
        f"| Cost of those tokens at list price | ${estimate_cost_usd(MODEL, sp, sc):.4f} | ESTIMATE |",
        "| Amount actually charged | free tier (`on_demand`), no charge expected; billed amount not visible to the code | UNAVAILABLE (read the Groq console) |",
        f"| Free-tier daily capacity | {TPD_LIMIT:,} tokens/day (provider message) ≈ {TPD_LIMIT / tok_per_q:.0f} answered queries/day at the measured rate | MEASURED limit / ESTIMATE capacity |",
        "| Incremental API cost of BM25, RRF and the cross-encoder | $0 — all run locally on CPU | MEASURED (no API call) |",
        f"| One-time: cross-encoder download | {model_info['download_bytes'] / 1e6:.1f} MB in {model_info['download_seconds_this_run']:.1f} s | MEASURED |",
        "| One-time: model loads / index builds | cross-encoder 0.15–0.77 s; MiniLM 0.02–0.08 s; dense index 0.4–0.6 s; BM25 index ≈ 2 ms | MEASURED (Phases 3–4) |",
        "| Disk: Python environment | 1.2 GB (torch 610 MB, needed only for the cross-encoder) | MEASURED (Phase 1) |",
        "",
    ]

    # ---- 6. implications
    b = bench[V1.split("+")[0]]
    L += [
        "## 6. Cost/latency implications of hybrid retrieval and reranking",
        "",
        f"- **Hybrid (BM25 + RRF):** +{b['bm25'] + b['rrf']:.2f} ms per query (≈ 0.5 % of retrieval), $0 API cost, ≈ 2 ms "
        "one-time index build. Negligible.",
        f"- **Cross-encoder reranking:** +{b['rerank']:.0f} ms median per query on CPU (p95 {b['rerank_p95']:.0f} ms) for v1 "
        "chunking; $0 API cost; one-time 92 MB download and ~0.2–0.8 s load; ~0.6 GB extra dependencies (torch). "
        "Relative to an LLM call of ≈ 1–2 s it adds ≈ 3–6 % to end-to-end latency.",
        "- **LLM cost is unchanged** by retrieval choices because the context stays at 4 chunks; tokens per query are driven "
        "by chunk length and the answer.",
        "- The dense refusal gate is the only component that *reduces* LLM cost (it skips the call), and on this "
        "evaluation set it never triggered for v1 (all 5 unanswerable questions were refused by the LLM itself).",
        "",
        "## 7. Unavailable measurements",
        "",
        "- Clean, comparable LLM and end-to-end latency for the three configurations on the evaluation set (runs were "
        "rate-limited at different times); GPU latency; concurrent-load behaviour; the actual billed amount.",
        "",
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "cost-latency-report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "cost-latency.json").write_text(
        json.dumps(
            {
                "retrieval_benchmark_median_ms": bench,
                "phase7_retrieval_median_ms": {
                    n: c["median_ms"]["retrieval_total"] for n, c in p7r["configs"].items()
                },
                "v1_cost_per_query_usd_estimate": per_q,
                "v1_tokens_per_answered_query": tok_per_q,
                "day13_tokens_spent": {"prompt": sp, "completion": sc},
                "day13_cost_estimate_usd": estimate_cost_usd(MODEL, sp, sc),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
